#!/usr/bin/env python3
"""Writes supabase/battle_words.sql: the level 1-6 words the battle server asks about, from ios/JuanGo/words.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BATCH = 500


def quote(s):
    return "'" + s.replace("'", "''") + "'"


def row(e):
    meanings = "array[" + ",".join(quote(z) for z in e["zh"]) + "]::text[]"
    return f"({quote(e['w'])},{int(e['lv'])},{quote(e.get('pos', ''))},{quote(e['zh'][0])},{meanings})"


entries, seen = [], set()
for e in json.loads((ROOT / "ios/JuanGo/words.json").read_text()):
    # a meaning has to fit on one answer button
    if e.get("lv") in list("123456") and e.get("zh") and len(e["zh"][0]) <= 16 and e["w"] not in seen:
        seen.add(e["w"])
        entries.append(e)

out = ["-- Generated by tools/battle/make_words.py. Run after battle.sql.", "begin;"]
for i in range(0, len(entries), BATCH):
    out.append("insert into public.battle_words (term, lv, pos, zh, meanings) values")
    out.append(",\n".join(row(e) for e in entries[i:i + BATCH]))
    out.append("on conflict (term) do update set lv = excluded.lv, pos = excluded.pos, zh = excluded.zh, meanings = excluded.meanings;")
out.append("commit;")
(ROOT / "supabase/battle_words.sql").write_text("\n".join(out) + "\n")
print(len(entries), "words")
